/** يتحقق من توازن ميزان المراجعة ويُنبّه إن كان غير متوازن */
handlers["ledger.verify_trial_balance"] = async () => {
  const { getTrialBalance } = await import("@/lib/accounting/ledger");
  const trial = await getTrialBalance({});

  if (trial.balanced) return { balanced: true, difference: 0 };

  await db.notification.create({
    data: {
      role: "admin",
      kind: "JOB_FAILED",
      severity: "critical",
      title: "ميزان المراجعة غير متوازن",
      body: `الفرق ${round2(trial.totalDebit - trial.totalCredit)} — يجب مراجعة القيود قبل إقفال الفترة.`,
      link: "/reports",
    },
  });

  await appendEvent({
    action: "UNBALANCED",
    entity: "Ledger",
    entityId: "trial_balance",
    actorType: "system",
    summary: `ميزان المراجعة غير متوازن بفرق ${round2(trial.totalDebit - trial.totalCredit)}`,
    payload: { debit: trial.totalDebit, credit: trial.totalCredit },
  });

  return { balanced: false, difference: round2(trial.totalDebit - trial.totalCredit) };
};

/** يتحقق من سلامة سلسلة سجل الأحداث — كشف أي تلاعب */
handlers["audit.verify_chain"] = async () => {
  const { verifyChain } = await import("./event-log");
  const result = await verifyChain();
  if (!result.ok) {
    await db.notification.create({
      data: {
        role: "admin",
        kind: "JOB_FAILED",
        severity: "critical",
        title: `سجل الأحداث مكسور (${result.breaks.length} موضع)`,
        body: result.breaks[0]?.reason ?? "تم اكتشاف عبث في السجل",
      },
    });
  }
  return result;
};

export function getHandler(type: string): JobHandler | undefined {
  return handlers[type];
}

export function registeredJobTypes() {
  return Object.keys(handlers);
}

