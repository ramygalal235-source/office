/** يفحص المهام المتأخرة ويُنشئ تنبيهًا لكل منها مرة واحدة فقط */
handlers["sla.scan_breaches"] = async () => {
  const now = new Date();
  const stale = new Date(now.getTime() - 60 * 60 * 1000);

  const overdue = await db.officeTask.findMany({
    where: {
      dueDate: { lt: now },
      status: { in: ["TODO", "IN_PROGRESS", "REVIEW"] },
      updatedAt: { lt: stale }, // لا نكرر التنبيه ما دامت لم تتغيّر الحالة
    },
    select: { id: true, title: true, dueDate: true, assignedTo: true },
    take: 100,
  });

  let notified = 0;
  for (const task of overdue) {
    const days = Math.floor((now.getTime() - new Date(task.dueDate).getTime()) / 86400000);
    await db.notification.create({
      data: {
        userId: task.assignedTo,
        kind: "SLA_BREACH",
        severity: days > 3 ? "critical" : "warning",
        title: `مهمة متأخرة ${days} يوم: ${task.title}`,
        body: `تجاوزت موعد الإنجاز بمقدار ${days} يوم.`,
        link: "/tasks",
      },
    });
    notified += 1;
  }

  return { scanned: overdue.length, notified };
};

/** ينبّه عند استحقاق ضريبي قادم خلال 7 أيام */
handlers["deadline.scan_upcoming"] = async () => {
  const now = new Date();
  const horizon = new Date(now.getTime() + 7 * 86400000);

  const upcoming = await db.taxObligation.findMany({
    where: { dueDate: { gte: now, lte: horizon }, status: { in: ["PENDING", "IN_PROGRESS"] } },
    include: { company: { select: { nameAr: true } } },
    take: 100,
  });

  let notified = 0;
  for (const o of upcoming) {
    await db.notification.create({
      data: {
        role: "accountant",
        kind: "DEADLINE",
        severity: "warning",
        title: `استحقاق خلال 7 أيام: ${o.title}`,
        body: `شركة ${o.company?.nameAr ?? "—"} — الاستحقاق ${new Date(o.dueDate).toLocaleDateString("ar-EG")}`,
        link: "/obligations",
      },
    });
    notified += 1;
  }

  return { scanned: upcoming.length, notified };
};

